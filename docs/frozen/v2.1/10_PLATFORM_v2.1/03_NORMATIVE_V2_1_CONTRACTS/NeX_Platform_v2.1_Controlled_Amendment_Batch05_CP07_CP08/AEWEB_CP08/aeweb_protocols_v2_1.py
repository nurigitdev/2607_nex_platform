from typing import Protocol, Mapping, Any

class InteractiveAgentFacade(Protocol):
    def submit_user_prompt(self, session_ref: str, request: Mapping[str, Any]) -> str: ...
    def get_agent_projection(self, agent_id: str) -> Mapping[str, Any]: ...

class NotificationProjectionClient(Protocol):
    def list_notifications(self, principal_ref: str) -> list[Mapping[str, Any]]: ...
    def mark_state(self, notification_id: str, state: str) -> None: ...

class HumanActionClient(Protocol):
    def get_action(self, action_ref: str) -> Mapping[str, Any]: ...
    def submit_action(self, action_ref: str, payload: Mapping[str, Any]) -> None: ...
