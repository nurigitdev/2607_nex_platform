from typing import Protocol, Mapping, Any

class AgentRegistryGovernanceClient(Protocol):
    def get_agent_profile(self, tenant_id: str, agent_id: str) -> Mapping[str, Any]: ...
    def apply_agent_governance_projection(self, decision: Mapping[str, Any]) -> None: ...

class SkillArtifactGovernanceClient(Protocol):
    def get_package_governance(self, package_ref: str, exact_version: str) -> Mapping[str, Any]: ...
    def get_publisher_key_status(self, publisher_ref: str, signing_key_ref: str | None) -> Mapping[str, Any]: ...

class TrustEvaluatorGovernanceClient(Protocol):
    def get_evaluator_profile(self, profile_ref: str, exact_version: str) -> Mapping[str, Any]: ...
